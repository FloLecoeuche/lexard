"""
Report generation for evaluation results.
"""

import json
from datetime import datetime
from pathlib import Path
from typing import Any

from .metrics import EvaluationMetrics, TestResult


def generate_report(
    metrics: EvaluationMetrics,
    results: list[TestResult],
    dataset_name: str = "Evaluation",
) -> str:
    """
    Generate markdown evaluation report.

    Args:
        metrics: Computed evaluation metrics
        results: List of test results
        dataset_name: Name of the dataset for the report title

    Returns:
        Markdown formatted report string
    """
    timestamp = datetime.now().isoformat()

    # Build failures section
    failures = [r for r in results if not r.passed]
    failures_section = _generate_failures_section(failures)

    # Build category breakdown
    category_section = _generate_category_breakdown(metrics.category_results)

    report = f"""# Evaluation Report: {dataset_name}

**Generated:** {timestamp}
**Total Test Cases:** {metrics.total_cases}

## Summary

| Metric | Value | Status |
|--------|-------|--------|
| Pass Rate | {metrics.pass_rate:.1%} | {_status_icon(metrics.pass_rate, 0.8)} |
| Grounding Rate | {metrics.grounding_rate:.1%} | {_status_icon(metrics.grounding_rate, 0.9)} |
| Hallucination Rate | {metrics.hallucination_rate:.1%} | {_status_icon(1 - metrics.hallucination_rate, 0.9)} |
| Refusal Appropriateness | {metrics.refusal_appropriateness:.1%} | {_status_icon(metrics.refusal_appropriateness, 0.9)} |
| Citation Accuracy | {metrics.citation_accuracy:.1%} | {_status_icon(metrics.citation_accuracy, 0.85)} |

## Targets

| Metric | Target | Actual | Status |
|--------|--------|--------|--------|
| Grounding Rate | ≥90% | {metrics.grounding_rate:.1%} | {"✅ PASS" if metrics.grounding_rate >= 0.9 else "❌ FAIL"} |
| Hallucination Rate | <10% | {metrics.hallucination_rate:.1%} | {"✅ PASS" if metrics.hallucination_rate < 0.1 else "❌ FAIL"} |

## Results by Category

{category_section}

## Confidence Distribution

| Level | Count | Percentage |
|-------|-------|------------|
| High | {metrics.confidence_distribution.get('high', 0)} | {_percentage(metrics.confidence_distribution.get('high', 0), metrics.total_cases)} |
| Medium | {metrics.confidence_distribution.get('medium', 0)} | {_percentage(metrics.confidence_distribution.get('medium', 0), metrics.total_cases)} |
| Low | {metrics.confidence_distribution.get('low', 0)} | {_percentage(metrics.confidence_distribution.get('low', 0), metrics.total_cases)} |
| Unknown | {metrics.confidence_distribution.get('unknown', 0)} | {_percentage(metrics.confidence_distribution.get('unknown', 0), metrics.total_cases)} |

## Refusal Analysis

- **Total Refusals:** {metrics.refusal_count}
- **Appropriate Refusals:** {metrics.appropriate_refusals}
- **Inappropriate Refusals:** {metrics.inappropriate_refusals}
- **Refusal Rate:** {metrics.refusal_rate:.1%}

{failures_section}

---

*Report generated by Lexard Evaluation Harness*
"""

    return report


def _status_icon(value: float, threshold: float) -> str:
    """Return status icon based on threshold."""
    if value >= threshold:
        return "✅"
    elif value >= threshold * 0.8:
        return "⚠️"
    else:
        return "❌"


def _percentage(count: int, total: int) -> str:
    """Calculate percentage string."""
    if total == 0:
        return "N/A"
    return f"{count / total:.1%}"


def _generate_category_breakdown(
    category_results: dict[str, dict[str, Any]],
) -> str:
    """Generate category breakdown table."""
    if not category_results:
        return "*No category data available*"

    lines = ["| Category | Total | Passed | Failed | Pass Rate |"]
    lines.append("|----------|-------|--------|--------|-----------|")

    for category, data in sorted(category_results.items()):
        lines.append(
            f"| {category} | {data['total']} | {data['passed']} | "
            f"{data['failed']} | {data['pass_rate']} |"
        )

    return "\n".join(lines)


def _generate_failures_section(failures: list[TestResult]) -> str:
    """Generate failures section."""
    if not failures:
        return "## Failed Test Cases\n\n*No failures - all tests passed!* 🎉"

    lines = ["## Failed Test Cases\n"]

    for result in failures:
        lines.append(f"### {result.case_id}")
        lines.append(f"- **Category:** {result.category}")
        lines.append(f"- **Expected:** {result.expected_behavior or 'N/A'}")
        lines.append(f"- **Actual:** {result.actual_behavior or 'N/A'}")
        if result.error:
            lines.append(f"- **Error:** {result.error}")
        if result.details.get("answer_preview"):
            lines.append(f"- **Answer preview:** {result.details['answer_preview']}")
        lines.append("")

    return "\n".join(lines)


def generate_json_report(
    metrics: EvaluationMetrics,
    results: list[TestResult],
    dataset_name: str = "Evaluation",
) -> dict[str, Any]:
    """
    Generate JSON evaluation report.

    Args:
        metrics: Computed evaluation metrics
        results: List of test results
        dataset_name: Name of the dataset

    Returns:
        Dictionary with report data
    """
    return {
        "metadata": {
            "dataset": dataset_name,
            "timestamp": datetime.now().isoformat(),
            "total_cases": metrics.total_cases,
        },
        "summary": {
            "pass_rate": metrics.pass_rate,
            "grounding_rate": metrics.grounding_rate,
            "hallucination_rate": metrics.hallucination_rate,
            "refusal_rate": metrics.refusal_rate,
            "refusal_appropriateness": metrics.refusal_appropriateness,
            "citation_accuracy": metrics.citation_accuracy,
            "average_confidence": metrics.average_confidence,
        },
        "targets": {
            "grounding_rate": {
                "target": 0.9,
                "actual": metrics.grounding_rate,
                "passed": metrics.grounding_rate >= 0.9,
            },
            "hallucination_rate": {
                "target": 0.1,
                "actual": metrics.hallucination_rate,
                "passed": metrics.hallucination_rate < 0.1,
            },
        },
        "category_results": metrics.category_results,
        "confidence_distribution": metrics.confidence_distribution,
        "results": [
            {
                "case_id": r.case_id,
                "category": r.category,
                "passed": r.passed,
                "expected_behavior": r.expected_behavior,
                "actual_behavior": r.actual_behavior,
                "has_citations": r.has_citations,
                "citation_count": r.citation_count,
                "confidence": r.confidence,
                "hallucination_flagged": r.hallucination_flagged,
                "error": r.error,
            }
            for r in results
        ],
    }


def save_report(
    metrics: EvaluationMetrics,
    results: list[TestResult],
    output_dir: Path | str,
    dataset_name: str = "evaluation",
    formats: list[str] | None = None,
) -> list[Path]:
    """
    Save evaluation report to files.

    Args:
        metrics: Computed evaluation metrics
        results: List of test results
        output_dir: Directory to save reports
        dataset_name: Name for the report files
        formats: List of formats to save ('md', 'json'). Defaults to both.

    Returns:
        List of paths to saved report files
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    formats = formats or ["md", "json"]
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    saved_files: list[Path] = []

    if "md" in formats:
        md_report = generate_report(metrics, results, dataset_name)
        md_path = output_dir / f"{dataset_name}_{timestamp}.md"
        md_path.write_text(md_report)
        saved_files.append(md_path)

    if "json" in formats:
        json_report = generate_json_report(metrics, results, dataset_name)
        json_path = output_dir / f"{dataset_name}_{timestamp}.json"
        json_path.write_text(json.dumps(json_report, indent=2))
        saved_files.append(json_path)

    return saved_files
